"""
01_dataset_report.py
--------------------
Inspect the Paper 3 inputs (copies of Paper 1 feature tables) and write dataset/dataset_report.md and
dataset/inspection/*.csv: sample sizes, covariate availability, missing features, duplicates, outliers, site counts.
Usage: python 01_dataset_report.py <project dir>
"""
import sys
from pathlib import Path
import numpy as np, pandas as pd

P = Path(sys.argv[1]); M = P / "dataset" / "metadata"; I = P / "dataset" / "inspection"
f = pd.read_csv(M / "features_v2.csv"); m = pd.read_csv(M / "meta_v2.csv"); o = pd.read_csv(M / "features_oasis1.csv")
cols = [c for c in f.select_dtypes("number").columns if c.startswith("mri_")]
d = f[f.has_mri == 1][["NACCID", "label"] + cols].merge(m[["NACCID", "NACCAGE", "sex", "mri_site", "mri_manufacturer"]], on="NACCID", how="left")
L = {0: "normal", 1: "MCI", 2: "dementia"}
rows = []
for k, g in d.groupby("label"):
    rows.append(dict(cohort="NACC", group=L[k], n=len(g), age_known=int((g.NACCAGE > 0).sum()), sex_known=int(g.sex.notna().sum()),
                     site_known=int(g.mri_site.notna().sum()), any_missing_feature=int(g[cols].isna().any(axis=1).sum())))
o["grp"] = pd.cut(pd.to_numeric(o.cdr), [-1, 0, 0.5, 9], labels=["CDR 0", "CDR 0.5", "CDR >=1"])
ocols = [c for c in o.columns if c.startswith("mri_")]
for k, g in o.groupby("grp", observed=True):
    rows.append(dict(cohort="OASIS-1", group=str(k), n=len(g), age_known=int(g.age.notna().sum()), sex_known=int(g.sex.notna().sum()),
                     site_known=len(g), any_missing_feature=int(g[ocols].isna().any(axis=1).sum())))
S = pd.DataFrame(rows); S.to_csv(I / "sample_summary.csv", index=False)

dup_ids = int(d.NACCID.duplicated().sum())
dup_rows = int(d[cols].round(6).duplicated().sum())
z = (d[cols] - d[cols].median()) / (1.4826 * (d[cols] - d[cols].median()).abs().median() + 1e-9)
out = (z.abs() > 6).sum().sort_values(ascending=False); out = out[out > 0]
out.rename("n_robust_z_gt6").to_csv(I / "outliers_by_feature.csv")
subj_out = (z.abs() > 6).sum(axis=1); worst = d.assign(n_extreme=subj_out)[["NACCID", "label", "n_extreme"]].sort_values("n_extreme", ascending=False).head(10)
worst.to_csv(I / "subjects_most_extreme.csv", index=False)
sites = d.groupby("mri_site").label.value_counts().unstack(fill_value=0); sites.to_csv(I / "site_by_label.csv")

md = lambda t: "\n".join(["| " + " | ".join(map(str, t.columns)) + " |", "|" + "---|" * t.shape[1]]
                         + ["| " + " | ".join(map(str, r)) + " |" for r in t.itertuples(index=False)])
rep = f"""# Dataset report — Paper 3 (generated by src/utils/01_dataset_report.py)

## Inputs and provenance
Copies of Paper 1 outputs (`paper1_multimodal/results/raw/features/`, copied 14 Oct 2026):
`features_v2.csv` (FastSurfer 2.6.0-dev regional volumes, per-mille of brain-mask volume, built by Paper 1
`45_build_features.py`), `meta_v2.csv` (label-file and DICOM fields), `label_gap.csv`, `features_oasis1.csv` (OASIS-1,
same code). No new image processing was done for Paper 3.

## Samples
{md(S)}

Age for NACC is the age at the baseline (label) UDS visit; sex is from DICOM headers.

## Checks
- Participants with MRI: {len(d)}; duplicated participant IDs: {dup_ids}; identical feature rows: {dup_rows}.
- MRI features: {len(cols)} (NACC), {len(ocols)} (OASIS-1). Features with any value beyond 6 robust SD: {len(out)}
  (`inspection/outliers_by_feature.csv`); the 10 participants with most extreme values are listed in
  `inspection/subjects_most_extreme.csv`. Extreme values are kept (they are real segmentations that passed Paper 1 QC);
  robust scaling is not used, so the sensitivity of the results to them is checked in the experiments.
- MRI sites with known site: {d.mri_site.nunique()}; site-by-label table in `inspection/site_by_label.csv`
  (site is associated with the label; see Paper 1 EXP024).
- Leakage: one MRI per participant; all splits are by participant.
- Laterality: OASIS-1 left-right direction cannot be verified, so cross-cohort analyses use left+right totals only.
"""
(P / "dataset" / "dataset_report.md").write_text(rep, encoding="utf-8"); print(rep); print(out.head(10)); print(worst)
